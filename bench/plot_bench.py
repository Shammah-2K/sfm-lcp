"""Turn bench/results.csv into Chapter 4's benchmark table and figures.

    python bench/plot_bench.py                 # newest model version of each model
    python bench/plot_bench.py --version lr-v2 --version iforest-v1

Writes docs/bench/summary.md (the table), latency.png and load.png. Only release
rows are used. Each figure value is the median over that device's runs; the
table gives the run count beside it. Needs matplotlib (bench/requirements.txt).
The CSV is the record; these outputs are regenerated from it, never edited.
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "bench" / "results.csv"
OUT = ROOT / "docs" / "bench"
MODELS = ["categoriser", "detector"]

# Reference palette slot 1 and text inks (dataviz skill, light mode).
INK = "#2a78d6"
TEXT = "#1f1f1e"
MUTED = "#6b6a63"
GRID = "#e4e3dc"


def load_rows(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f) if r["build_mode"] == "release"]


def pick_versions(rows: list[dict], wanted: list[str]) -> dict[str, str]:
    """model -> model_version: as asked, else the most recently measured."""
    chosen = {}
    for model in MODELS:
        mine = [r for r in rows if r["model"] == model]
        named = [r for r in mine if r["model_version"] in wanted]
        pool = named or mine
        if pool:
            chosen[model] = max(pool, key=lambda r: r["timestamp_utc"])["model_version"]
    return chosen


def device_label(r: dict) -> str:
    ram = r["ram_total_mb"]
    gb = f", {int(ram) / 1024:.1f} GB" if ram else ""
    return f"{r['device_manufacturer']} {r['device_model']}{gb}"


def summarise(rows: list[dict], versions: dict[str, str]) -> list[dict]:
    """One line per (model, device): medians over runs."""
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in rows:
        if versions.get(r["model"]) == r["model_version"]:
            groups[(r["model"], device_label(r))].append(r)

    def med(rs: list[dict], key: str) -> float | None:
        vals = [float(r[key]) for r in rs if r[key] != ""]
        return median(vals) if vals else None

    out = []
    for (model, device), rs in sorted(groups.items()):
        rss = [float(r["rss_after_load_mb"]) - float(r["rss_before_load_mb"]) for r in rs]
        out.append({
            "model": model,
            "model_version": rs[0]["model_version"],
            "device": device,
            "api": rs[0]["android_api"],
            "runs": len(rs),
            "calls_per_run": rs[0]["n"],
            "p50_us": med(rs, "p50_us"),
            "p95_us": med(rs, "p95_us"),
            "max_us": max(float(r["max_us"]) for r in rs),
            "first_call_us": med(rs, "first_call_us"),
            "load_ms": med(rs, "load_ms"),
            "model_kb": float(rs[0]["model_bytes"]) / 1024,
            "rss_delta_mb": median(rss),
            "app_pss_mb": med(rs, "app_pss_mb"),
            "git_sha": ",".join(sorted({r["git_sha"] for r in rs})),
        })
    return out


def fmt(v: float | None, digits: int = 0) -> str:
    return "–" if v is None else f"{v:,.{digits}f}"


def write_table(summary: list[dict], path: Path) -> None:
    lines = [
        "# On-device benchmark (generated by bench/plot_bench.py; do not edit)",
        "",
        "Medians over runs; each run is a fresh app start on the phone, release build.",
        "Latency is one prediction through the model's public call, in microseconds.",
        "",
        "| Model | Version | Device | API | Runs | Calls/run | p50 µs | p95 µs | Max µs "
        "| First call µs | Load ms | Model KB | RSS Δ MB | App PSS MB | Commit |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for s in summary:
        lines.append(
            f"| {s['model']} | {s['model_version']} | {s['device']} | {s['api']} "
            f"| {s['runs']} | {s['calls_per_run']} | {fmt(s['p50_us'])} | {fmt(s['p95_us'])} "
            f"| {fmt(s['max_us'])} | {fmt(s['first_call_us'])} | {fmt(s['load_ms'], 1)} "
            f"| {fmt(s['model_kb'])} | {fmt(s['rss_delta_mb'], 1)} | {fmt(s['app_pss_mb'], 1)} "
            f"| {s['git_sha']} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _style(ax, xlabel: str) -> None:
    ax.set_xlabel(xlabel, color=MUTED, fontsize=9)
    ax.tick_params(colors=MUTED, labelsize=9, length=0)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.set_xlim(left=0)


def plot_latency(summary: list[dict], path: Path) -> None:
    """Dot plot per model: filled dot p50, open dot p95, joined by a thin line.
    One panel per model; their scales differ, so each has its own axis."""
    import matplotlib.pyplot as plt

    present = [m for m in MODELS if any(s["model"] == m for s in summary)]
    devices = sorted({s["device"] for s in summary})
    fig, axes = plt.subplots(
        1, len(present), figsize=(4.2 * len(present), 0.6 * len(devices) + 1.4),
        squeeze=False, sharey=True,
    )
    for ax, model in zip(axes[0], present):
        rows = {s["device"]: s for s in summary if s["model"] == model}
        for y, device in enumerate(devices):
            s = rows.get(device)
            if s is None:
                continue
            ax.plot([s["p50_us"], s["p95_us"]], [y, y], color=INK, linewidth=2,
                    solid_capstyle="round", zorder=2)
            ax.scatter([s["p50_us"]], [y], s=64, color=INK, edgecolors="white",
                       linewidths=2, zorder=3, label="p50" if y == 0 else None)
            ax.scatter([s["p95_us"]], [y], s=64, facecolors="white", edgecolors=INK,
                       linewidths=2, zorder=3, label="p95" if y == 0 else None)
            ax.annotate(f"{s['p95_us']:,.0f}", (s["p95_us"], y), xytext=(8, 0),
                        textcoords="offset points", va="center", fontsize=8, color=TEXT)
        ax.set_title(f"{model} ({rows[next(iter(rows))]['model_version']})",
                     loc="left", fontsize=10, color=TEXT)
        ax.set_yticks(range(len(devices)), devices, color=TEXT)
        ax.set_ylim(-0.6, len(devices) - 0.4)
        ax.margins(x=0.25)
        _style(ax, "microseconds per prediction")
    handles, labels = axes[0][0].get_legend_handles_labels()
    fig.legend(handles, labels, frameon=False, fontsize=8, ncol=2, loc="upper right",
               labelcolor=TEXT)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(path, dpi=200)
    plt.close(fig)


def plot_load(summary: list[dict], path: Path) -> None:
    """Horizontal bars: median cold load time per model and device."""
    import matplotlib.pyplot as plt

    present = [m for m in MODELS if any(s["model"] == m for s in summary)]
    devices = sorted({s["device"] for s in summary})
    fig, axes = plt.subplots(
        1, len(present), figsize=(4.2 * len(present), 0.6 * len(devices) + 1.4),
        squeeze=False, sharey=True,
    )
    for ax, model in zip(axes[0], present):
        rows = {s["device"]: s for s in summary if s["model"] == model}
        for y, device in enumerate(devices):
            s = rows.get(device)
            if s is None or s["load_ms"] is None:
                continue
            ax.barh(y, s["load_ms"], height=0.5, color=INK, zorder=2)
            ax.annotate(f"{s['load_ms']:,.0f} ms", (s["load_ms"], y), xytext=(6, 0),
                        textcoords="offset points", va="center", fontsize=8, color=TEXT)
        ax.set_title(model, loc="left", fontsize=10, color=TEXT)
        ax.set_yticks(range(len(devices)), devices, color=TEXT)
        ax.margins(x=0.25)
        _style(ax, "milliseconds to load (cold)")
    fig.tight_layout()
    fig.savefig(path, dpi=200)
    plt.close(fig)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--version", action="append", default=[],
                   help="model version to report (repeat per model)")
    p.add_argument("--csv", type=Path, default=RESULTS)
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()

    rows = load_rows(args.csv)
    if not rows:
        raise SystemExit(f"no release rows in {args.csv}; run bench/run_bench.py first")
    versions = pick_versions(rows, args.version)
    summary = summarise(rows, versions)
    args.out.mkdir(parents=True, exist_ok=True)
    write_table(summary, args.out / "summary.md")
    plot_latency(summary, args.out / "latency.png")
    plot_load(summary, args.out / "load.png")
    print(f"versions: {versions}; {len(summary)} lines -> {args.out}")


if __name__ == "__main__":
    main()

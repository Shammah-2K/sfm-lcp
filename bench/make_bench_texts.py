"""Write the categoriser benchmark's input descriptions into the bench build.

The descriptions are the 300 held-out cases that ml/train_categoriser.py writes
for the parity test (mobile/test/fixtures/categoriser_parity.json). They go into
a Dart file, not an asset, so the real app's APK never carries them: only the
bench entrypoint imports the file.

Run after retraining the categoriser:
    python bench/make_bench_texts.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "mobile" / "test" / "fixtures" / "categoriser_parity.json"
OUT = ROOT / "mobile" / "lib" / "bench" / "bench_texts.dart"


def dart_string(text: str) -> str:
    """A single-quoted Dart literal; json.dumps escapes everything but quotes."""
    body = json.dumps(text, ensure_ascii=False)[1:-1]
    body = body.replace("\\\"", "\"").replace("'", "\\'").replace("$", "\\$")
    return f"'{body}'"


def render(texts: list[str], model_version: str) -> str:
    lines = [
        "// GENERATED by bench/make_bench_texts.py from",
        "// mobile/test/fixtures/categoriser_parity.json "
        f"(model {model_version}). Do not edit.",
        "",
        "/// Held-out descriptions the categoriser benchmark cycles through.",
        "const List<String> benchTexts = [",
        *[f"  {dart_string(t)}," for t in texts],
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parity = json.loads(FIXTURE.read_text(encoding="utf-8"))
    texts = [c["text"] for c in parity["cases"]]
    OUT.write_text(render(texts, parity["model_version"]), encoding="utf-8", newline="\n")
    print(f"{len(texts)} descriptions -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
